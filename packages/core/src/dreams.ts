/** Shared semantics for conversation and material-to-record flows. */
export const DREAM_CONTEXT_RULE = `【梦境】body.nature 或 nature 为 dream 的记录是睡梦内容，日期是记录者醒来的日期，不是梦中事件的现实发生日期。梦境与现实日记分开检索；未明确询问梦境时，不能把梦境当作现实经历。用户询问梦境时可查找、引用、比较梦境原文，并保留“梦见／梦里”的语境。区分原文事实、用户表达的感受与推测；联想现实需明确依据，不断言潜意识、象征含义、诊断或预兆。数量只能称“记录了几条梦境”，不能据此说做梦频率变多或减少。梦中人物、地点、关系、观影、待办不证明现实见面、到访、矛盾或看过电影，不自动创建现实对象、任务或周期标记。仅在用户明确要求记梦时拟写 kind=journal、nature=dream 的记录；不得将梦中情节拆成现实操作。引用原文只读，不替用户改写细节，分析也不要自动追加到记录。`;

export function asksAboutDreams(message: string): boolean {
  return /梦境|梦见|梦到|做梦|噩梦|恶梦|解梦|梦里|梦中|(?:我的|这些|那些|几个|几条|多少|什么|哪些|这个|那个|上次|之前的|以前的|反复的|重复的|相似的)梦|记录.{0,6}梦|梦.{0,6}(记录|相似|重复|场景|感受|回顾)/.test(message);
}

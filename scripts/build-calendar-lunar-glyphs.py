"""Extract existing Huiwen Mincho lunar glyph outlines; no runtime font dependency.

Usage: python build-calendar-lunar-glyphs.py --font path/to/汇文明朝体.ttf
Requires fontTools (may be installed in a separate tool directory via PYTHONPATH).
The source font is not redistributed. Only selected glyphs are emitted (twelve by default).
"""
import argparse
import hashlib
import json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

parser = argparse.ArgumentParser()
parser.add_argument("--font", type=Path, required=True)
parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "apps/web/src/assets/calendar-lunar-glyphs.svg")
parser.add_argument("--characters", default="初一二三四五六七八九十廿", help="Explicit outline subset; defaults to the production lunar characters")
args = parser.parse_args()
font = TTFont(args.font)
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
family = font["name"].getDebugName(1) or "Huiwen Mincho"
sha = hashlib.sha256(args.font.read_bytes()).hexdigest()
parts = [f'<svg xmlns="http://www.w3.org/2000/svg"><!-- Huiwen Mincho local outline slices; source SHA256 {sha}; generated by scripts/build-calendar-lunar-glyphs.py --><defs>']
manifest = []
for char in dict.fromkeys(args.characters):
    name = cmap.get(ord(char))
    if not name or name == ".notdef":
        raise RuntimeError(f"Missing required glyph {char}")
    glyph = glyphs[name]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    # Uniformly normalize actual ink bounds into a square cell. No X/Y stretching.
    scale = 900 / max(x1 - x0, y1 - y0)
    dx, dy = 500 - (x0 + x1) * scale / 2, 500 + (y0 + y1) * scale / 2
    pen = SVGPathPen(glyphs, ntos=lambda value: f"{value:.2f}".rstrip("0").rstrip("."))
    glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, dx, dy)))
    ident = f"calendar-lunar-u{ord(char):04x}"
    parts.append(f'<symbol id="{ident}" viewBox="0 0 1000 1000"><path fill="currentColor" fill-rule="nonzero" d="{pen.getCommands()}"/></symbol>')
    manifest.append({"char": char, "id": ident, "glyph": name, "scale": scale, "sourceBounds": bounds.bounds})
parts.append("</defs></svg>\n")
args.output.write_text("\n".join(parts), encoding="utf-8")
print(json.dumps({"family": family, "sourceSHA256": sha, "glyphs": len(manifest), "bytes": args.output.stat().st_size, "manifest": manifest}, ensure_ascii=False))
